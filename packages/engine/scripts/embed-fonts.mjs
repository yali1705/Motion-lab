// Embeds the bundled Heebo font subsets as base64 data URLs so that the
// editor preview and the headless render use byte-identical font files
// without any network access.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const assets = join(here, '..', 'assets');
const out = join(here, '..', 'src', 'fonts.generated.ts');

const faces = [
  {
    file: 'heebo-latin.woff2',
    unicodeRange:
      'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD',
  },
  {
    file: 'heebo-hebrew.woff2',
    unicodeRange: 'U+0307-0308, U+0590-05FF, U+200C-2010, U+20AA, U+25CC, U+FB1D-FB4F',
  },
];

const entries = faces.map((f) => {
  const b64 = readFileSync(join(assets, f.file)).toString('base64');
  return `  {\n    family: 'Heebo',\n    weight: '300 900',\n    style: 'normal',\n    unicodeRange: '${f.unicodeRange}',\n    src: 'data:font/woff2;base64,${b64}',\n  }`;
});

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by scripts/embed-fonts.mjs — do not edit.\n// Heebo (SIL Open Font License 1.1), subsets: latin, hebrew.\nexport interface EmbeddedFontFace {\n  family: string;\n  weight: string;\n  style: string;\n  unicodeRange: string;\n  src: string;\n}\n\nexport const EMBEDDED_FONT_FACES: EmbeddedFontFace[] = [\n${entries.join(',\n')},\n];\n`,
);
console.log(`[engine] embedded ${faces.length} font faces -> ${out}`);
